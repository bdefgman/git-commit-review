"""diff 过滤：文件筛选、生成代码识别、密钥扫描、行内忽略指令。"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Dict, Iterable, List, Optional, Pattern, Set, Tuple

from .config import Config
from .gitio import ChangedFile


@dataclass
class SkippedFile:
    path: str
    reason: str


@dataclass
class SecretHit:
    path: str
    line: int
    rule: str
    masked: str


@dataclass
class IgnoreRules:
    # (文件, 行号) -> 规则集合；空集合表示忽略该行全部规则
    line_rules: Dict[Tuple[str, int], Set[str]] = field(default_factory=dict)
    # 文件 -> 规则集合；空集合表示忽略该文件全部规则
    file_rules: Dict[str, Set[str]] = field(default_factory=dict)

    def is_ignored(self, path: str, line: int, rule_id: str) -> bool:
        file_scope = self.file_rules.get(path)
        if file_scope is not None and (not file_scope or rule_id in file_scope):
            return True
        for target in (line, line - 1):
            line_scope = self.line_rules.get((path, target))
            if line_scope is not None and (not line_scope or rule_id in line_scope):
                return True
        return False


_PATTERN_CACHE: Dict[str, Pattern[str]] = {}

_GENERATED_MARKERS = (
    "@Generated",
    "DO NOT EDIT",
    "Code generated by",
    "此文件由",
    "自动生成，请勿修改",
)

SECRET_RULES: List[Tuple[str, Pattern[str]]] = [
    ("private-key", re.compile(r"-----BEGIN (?:[A-Z]+ )?PRIVATE KEY-----")),
    ("aws-access-key", re.compile(r"\b(?:AKIA|ASIA)[0-9A-Z]{16}\b")),
    (
        "generic-secret",
        re.compile(
            r"(?i)\b(?:api[_-]?key|secret|token|password|passwd|pwd)\b\s*[:=]\s*[\"'][^\"'\s]{8,}[\"']"
        ),
    ),
    ("sk-key", re.compile(r"\bsk-[A-Za-z0-9]{20,}\b")),
    ("gitlab-token", re.compile(r"\bglpat-[A-Za-z0-9_\-]{20,}\b")),
]


def glob_to_regex(pattern: str) -> Pattern[str]:
    """把 glob 转成正则，支持 **（匹配任意层目录）、*、?。"""
    output: List[str] = ["^"]
    index = 0
    while index < len(pattern):
        char = pattern[index]
        if char == "*":
            if pattern.startswith("**/", index):
                output.append("(?:.*/)?")
                index += 3
                continue
            if pattern.startswith("**", index):
                output.append(".*")
                index += 2
                continue
            output.append("[^/]*")
        elif char == "?":
            output.append("[^/]")
        elif char in ".+()|[]{}^$\\":
            output.append("\\" + char)
        else:
            output.append(char)
        index += 1
    output.append("$")
    return re.compile("".join(output))


def matches_any(path: str, patterns: Iterable[str]) -> bool:
    """匹配路径；不含 / 的模式（如 *.java）只匹配文件名。"""
    name = path.rsplit("/", 1)[-1]
    for pattern in patterns:
        regex = _PATTERN_CACHE.get(pattern)
        if regex is None:
            regex = glob_to_regex(pattern)
            _PATTERN_CACHE[pattern] = regex
        if regex.match(path):
            return True
        if "/" not in pattern and regex.match(name):
            return True
    return False


def select_files(files: List[ChangedFile], cfg: Config) -> Tuple[List[ChangedFile], List[SkippedFile]]:
    kept: List[ChangedFile] = []
    skipped: List[SkippedFile] = []
    for item in files:
        reason = _skip_reason(item, cfg)
        if reason:
            skipped.append(SkippedFile(item.path, reason))
        else:
            kept.append(item)
    return kept, skipped


def detect_generated(content: Optional[str]) -> bool:
    if not content:
        return False
    return any(marker in content for marker in _GENERATED_MARKERS)


def scan_secrets(files: List[ChangedFile]) -> List[SecretHit]:
    hits: List[SecretHit] = []
    for item in files:
        for line in item.added_lines():
            for rule, regex in SECRET_RULES:
                matched = regex.search(line.text)
                if matched and line.new_no:
                    hits.append(SecretHit(item.path, line.new_no, rule, _mask(matched.group(0))))
    return hits


def collect_ignores(
    files: List[ChangedFile],
    directive: str,
    contents: Optional[Dict[str, str]] = None,
) -> IgnoreRules:
    """解析忽略指令。

    - 文件级（ai-review-ignore-file）：扫描整个暂存区版本，历史提交里写的标记同样生效
    - 行级（ai-review-ignore）：只看本次新增行
    """
    rules = IgnoreRules()
    contents = contents or {}
    file_pattern = re.compile(
        re.escape(directive) + r"-file[ \t]*(?:[:：][ \t]*([A-Za-z0-9_,\- \t]+))?"
    )
    line_pattern = re.compile(
        re.escape(directive) + r"(?!-file)[ \t]*(?:[:：][ \t]*([A-Za-z0-9_,\- \t]+))?"
    )

    for item in files:
        text = contents.get(item.path)
        if text is None:
            text = "\n".join(line.text for line in item.added_lines())
        file_matched = file_pattern.search(text)
        if file_matched:
            rules.file_rules[item.path] = _parse_rule_ids(file_matched.group(1))

        for line in item.added_lines():
            if line.new_no is None:
                continue
            line_matched = line_pattern.search(line.text)
            if line_matched:
                rules.line_rules[(item.path, line.new_no)] = _parse_rule_ids(line_matched.group(1))

    return rules


def _parse_rule_ids(raw: Optional[str]) -> Set[str]:
    return {part.strip() for part in (raw or "").split(",") if part.strip()}


def _skip_reason(item: ChangedFile, cfg: Config) -> Optional[str]:
    if item.binary:
        return "二进制文件"
    if item.status == "D":
        return "文件被删除"
    if not item.hunks:
        return "没有内容变更"
    if not matches_any(item.path, cfg.review.include):
        return "不在 include 范围"
    if matches_any(item.path, cfg.review.exclude):
        return "命中 exclude 规则"
    return None


def _mask(value: str) -> str:
    if len(value) <= 6:
        return "***"
    return value[:6] + "***"
